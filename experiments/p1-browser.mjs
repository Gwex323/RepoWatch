import { createRequire } from "node:module";
import { spawn } from "node:child_process";
import { mkdir } from "node:fs/promises";
import { resolve } from "node:path";
import { createServer } from "node:net";
const require = createRequire(resolve("frontend/package.json"));
const { chromium, expect } = require("@playwright/test");
const root = resolve(".cache/p1-browser", String(Date.now()));
await mkdir(root, { recursive: true });
const port = await new Promise((done, fail) => { const socket = createServer(); socket.once("error", fail); socket.listen(0, "127.0.0.1", () => { const value = socket.address().port; socket.close(() => done(value)); }); });
const host = spawn(resolve("backend/.venv/Scripts/python.exe"), ["-X", "utf8", "experiments/p1_browser_host.py", "--data-dir", resolve(root, "data"), "--port", String(port)], { windowsHide: true, stdio: ["ignore", "pipe", "pipe"] });
let browser;
let page;
const httpFailures = [];
const pageFailures = [];
const loaded = [];
let hostErrors = "";
host.stderr.on("data", chunk => { hostErrors = (hostErrors + chunk.toString()).slice(-4000); });
try {
  const setup = await new Promise((done, fail) => {
    let buffered = "";
    const timeout = setTimeout(() => fail(new Error("browser fixture startup timed out")), 20000);
    host.once("exit", () => { clearTimeout(timeout); fail(new Error("browser fixture host exited: " + hostErrors.replaceAll("test-browser-secret-key", "[REDACTED]"))); });
    host.stdout.on("data", chunk => { buffered += chunk.toString(); const end = buffered.indexOf("\n"); if (end !== -1) { clearTimeout(timeout); done(JSON.parse(buffered.slice(0, end))); } });
  });
  host.stderr.on("data", () => {});
  browser = await chromium.launch({ channel: "msedge", headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  page = await context.newPage();
  page.on("requestfailed", request=>pageFailures.push(request.failure()?.errorText));
  page.on("response", response => { loaded.push({path:new URL(response.url()).pathname,status:response.status()}); if(response.status()>=400) httpFailures.push({path:new URL(response.url()).pathname,status:response.status()}); });
  const failures = [];
  page.on("console", message => { if(message.type()==="error") pageFailures.push(message.text()); });
  page.on("pageerror", error => { failures.push(error.name); pageFailures.push(error.message); });
  const mutations = [];
  page.on("request", request => { if (request.method() === "POST") mutations.push(request.url().split("?")[0]); });
  const base = `http://127.0.0.1:${port}`;
  for (let attempt = 0; attempt < 40; attempt++) { try { const response = await fetch(base + "/api/v1/health"); if (response.ok) break; } catch {} await new Promise(done => setTimeout(done, 100)); }
  await page.goto(base + "/#session=" + setup.bootstrap);
  await expect(page.getByRole("heading", { name: "任务队列" })).toBeVisible();
  const reconnect = page.waitForRequest(async request => request.url().includes("/events/stream") && Boolean((await request.allHeaders())["last-event-id"]), { timeout: 15000 });
  await expect(page.getByText("常规队列已暂停", { exact: true })).toBeVisible();
  await page.locator(".task-row").first().click();
  await expect(page.getByRole("heading", { name: "任务详情" })).toBeVisible();
  await expect(page.getByText("无进展窗口与检测阈值", { exact: true })).toBeVisible();
  await page.getByLabel("补充信息", { exact: true }).fill("浏览器实际补充的核验材料");
  await page.getByRole("button", { name: "保存补充材料", exact: true }).click();
  await expect(page.getByRole("status")).toHaveText("操作已保存。");
  const grant = page.locator("form").filter({ has: page.getByRole("button", { name: "确认有限预算", exact: true }) });
  await grant.getByLabel("依据与处理方案").fill("保留原账本并人工追加有限额度");
  await grant.getByRole("button", { name: "确认有限预算" }).click();
  await expect(page.getByRole("status")).toContainText("有限预算调整已保存");
  let state = await page.evaluate(async () => (await fetch("/api/v1/state")).json());
  let task = state.tasks.find(item => item.id === setup.task_id);
  expect(task.budget.used.tokens).toBe(10);
  expect(task.budget.reserved.tokens).toBe(20);
  expect(state.control.paused).toBe(1);
  await page.getByRole("button", { name: "明确恢复", exact: true }).click();
  await expect(page.getByRole("alert")).toContainText("前置条件");
  await page.getByRole("button", { name: /待人工事项/ }).click();
  await page.getByLabel("实质处理依据").fill("已补充输入，并明确改变排查策略");
  await page.getByLabel("授权一次有界重试").check();
  await page.getByLabel("具体步骤（每行一步）").fill("核验新增复现材料\n按新证据执行一次验证");
  await page.getByLabel("可观察的成功条件").fill("取得与新复现关联的实际证据");
  await page.getByRole("button", { name: "提交处理结果" }).click();
  await expect(page.getByRole("status")).toContainText("原因处理已保存");
  await page.getByRole("button", { name: "明确恢复", exact: true }).click();
  await expect(page.getByText("常规队列已放行", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "全局暂停", exact: true }).click();
  await expect(page.getByText("常规队列已暂停", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "供应商", exact: true }).click();
  await page.getByLabel("名称", { exact: true }).fill("browser-gateway");
  await page.getByLabel("API 地址").fill("https://unused.example/v1");
  await page.getByLabel("密钥", { exact: true }).fill("test-browser-secret-key");
  await page.getByLabel(/首个模型/).fill("manual-model");
  await page.getByRole("button", { name: "保存配置", exact: true }).click();
  await expect(page.getByRole("heading", { name: "browser-gateway", exact: true })).toBeVisible();
  expect(await page.locator("body").innerText()).not.toContain("test-browser-secret-key");
  await page.getByRole("button", { name: "角色模型", exact: true }).click();
  await page.getByLabel("模型", { exact: true }).fill("manual-model");
  await page.getByRole("button", { name: "保存角色绑定" }).click();
  await expect(page.getByRole("status")).toContainText("角色绑定已保存");
  await page.getByRole("button", { name: "诊断", exact: true }).click();
  await page.getByLabel("测试类型").selectOption("storage_probe");
  await page.getByRole("button", { name: "明确发起诊断" }).click();
  await expect(page.getByRole("status")).toContainText("诊断已登记");
  state = await page.evaluate(async () => (await fetch("/api/v1/state")).json());
  expect(state.tasks.length).toBe(2);
  expect(state.control.paused).toBe(1);
  expect(state.diagnostics[0].state).toBe("queued");
  await reconnect;
  const beforeReload = mutations.length;
  await page.reload();
  await expect(page.getByRole("heading", { name: "任务队列" })).toBeVisible();
  expect(mutations.length).toBe(beforeReload);
  await page.screenshot({ path: resolve(root, "control.png"), fullPage: true });
  expect(failures).toEqual([]);
  console.log(JSON.stringify({ status: "passed", browser: "Edge", checks: ["session", "progress_window", "sse_cursor_reconnect", "supplement", "finite_budget_preserves_usage", "blocked_resume_rejected", "bounded_retry", "explicit_resume", "provider", "role_binding", "diagnostic_intent", "reload_does_not_start_work"], screenshot: resolve(root, "control.png") }));
} catch(error) {
  if(page) { console.log(JSON.stringify({httpFailures, pageFailures, loaded, html:(await page.content()).slice(0,1200), visible: (await page.locator("body").innerText()).replaceAll("test-browser-secret-key","[REDACTED]").slice(0,2500)})); await page.screenshot({path:resolve(root,"failure.png"),fullPage:true}); }
  throw error;
} finally {
  if (browser) await browser.close();
  host.kill();
}
